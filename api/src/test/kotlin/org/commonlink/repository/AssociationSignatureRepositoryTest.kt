package org.commonlink.repository

import org.commonlink.entity.AssociationSignature
import org.commonlink.entity.MandateEligibility
import org.commonlink.entity.SignatureMode
import org.junit.jupiter.api.Assertions.assertArrayEquals
import org.junit.jupiter.api.Assertions.assertEquals
import org.junit.jupiter.api.Assertions.assertFalse
import org.junit.jupiter.api.Assertions.assertTrue
import org.junit.jupiter.api.Test
import org.junit.jupiter.api.assertThrows
import org.springframework.beans.factory.annotation.Autowired
import org.springframework.dao.DataIntegrityViolationException
import org.springframework.jdbc.core.JdbcTemplate
import java.time.Instant
import java.time.temporal.ChronoUnit
import java.util.UUID

/**
 * `association_signature` (V98) on the real Flyway schema, validated against [AssociationSignature]: the suite's H2
 * schema is generated by Hibernate and carries neither the CHECK constraints nor the ON DELETE CASCADE.
 */
class AssociationSignatureRepositoryTest : RealPostgresTest() {

    @Autowired private lateinit var signatureRepository: AssociationSignatureRepository
    @Autowired private lateinit var userRepository: UserRepository
    @Autowired private lateinit var profileRepository: AssociationProfileRepository
    @Autowired private lateinit var jdbcTemplate: JdbcTemplate

    private val now: Instant = Instant.now().truncatedTo(ChronoUnit.MICROS)

    private fun newAssociationId(): UUID {
        val user = userRepository.save(TestFixtures.associationUser(email = "sig-${UUID.randomUUID()}@example.com"))
        val identifier = (100_000_000..999_999_999).random().toString()
        return profileRepository.save(TestFixtures.associationProfile(user, identifier = identifier)).id!!
    }

    @Test
    fun `round-trips an image signature and replaces it on the same key`() {
        val id = newAssociationId()
        val png = byteArrayOf(0x89.toByte(), 0x50, 0x4E, 0x47, 1, 2, 3)

        signatureRepository.saveAndFlush(AssociationSignature(id, SignatureMode.UPLOAD, png, "image/png", now, now))
        val stored = signatureRepository.findById(id).orElseThrow()
        assertEquals(SignatureMode.UPLOAD, stored.mode)
        assertArrayEquals(png, stored.image)
        assertEquals(now, stored.attestedAt)

        signatureRepository.saveAndFlush(AssociationSignature(id, SignatureMode.DRAWN, png, "image/png", now, now))
        assertEquals(1L, jdbcTemplate.queryForObject(
            "SELECT count(*) FROM association_signature WHERE association_id = ?", Long::class.java, id,
        ))
        assertEquals("DRAWN", jdbcTemplate.queryForObject(
            "SELECT mode FROM association_signature WHERE association_id = ?", String::class.java, id,
        ))
    }

    /** V98: every signature is an image — a row without image or content type, or in the withdrawn TYPED mode, is refused. */
    @Test
    fun `the image and its content type are mandatory, the TYPED mode is refused`() {
        val insert = "INSERT INTO association_signature (association_id, mode, image, content_type, attested_at, updated_at) " +
            "VALUES (?, ?, ?, ?, now(), now())"

        assertThrows<DataIntegrityViolationException> {
            jdbcTemplate.update(insert, newAssociationId(), "DRAWN", null, "image/png")
        }
        assertThrows<DataIntegrityViolationException> {
            jdbcTemplate.update(insert, newAssociationId(), "UPLOAD", byteArrayOf(1), null)
        }
        assertThrows<DataIntegrityViolationException> {
            jdbcTemplate.update(insert, newAssociationId(), "TYPED", byteArrayOf(1), "image/png")
        }
    }

    /** V98 recreated the V35 CHECK without PUBLIC_UTILITY_66: it must list exactly the [MandateEligibility] entries. */
    @Test
    fun `the fiscal mandate eligibility CHECK constraint lists exactly the enum values`() {
        val definition = jdbcTemplate.queryForObject(
            "SELECT pg_get_constraintdef(oid) FROM pg_constraint WHERE conname = 'fiscal_mandate_eligibility_check'",
            String::class.java,
        )!!
        val listed = Regex("'([A-Z0-9_]+)'").findAll(definition).map { it.groupValues[1] }.toSet()

        assertEquals(MandateEligibility.entries.map { it.name }.toSet(), listed)
    }

    @Test
    fun `the mode CHECK constraint lists exactly the enum values`() {
        val definition = jdbcTemplate.queryForObject(
            "SELECT pg_get_constraintdef(oid) FROM pg_constraint WHERE conname = 'association_signature_mode_check'",
            String::class.java,
        )!!
        val listed = Regex("'([A-Z_]+)'").findAll(definition).map { it.groupValues[1] }.toSet()

        assertEquals(SignatureMode.entries.map { it.name }.toSet(), listed)
    }

    @Test
    fun `deleting the association profile deletes its signature`() {
        val id = newAssociationId()
        signatureRepository.saveAndFlush(AssociationSignature(id, SignatureMode.UPLOAD, byteArrayOf(1), "image/png", now, now))
        assertTrue(signatureRepository.existsById(id))

        jdbcTemplate.update("DELETE FROM association_profiles WHERE id = ?", id)

        assertFalse(signatureRepository.existsById(id))
    }
}
